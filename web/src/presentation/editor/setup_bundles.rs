pub(super) fn use_setup_workspaces(
    setup_a: &SetupA,
) -> (
    SetupB,
    keymap::LayerActions,
    keymap::BindingActions,
    keymap::MacroActions,
) {
    let model = &setup_a.model;
    let current_scope = &setup_a.current_scope;
    let runtime = &setup_a.runtime;
    let workspace = setup_a.workspace;
    let version = setup_a.version;
    let adapter = &setup_a.adapter;
    let instance_selection = setup_a.instance_selection;
    let layout_owner = &setup_a.layout_owner;
    let guide_preferences = setup_a.guide_preferences;
    let keymap_layer_id = setup_a.keymap_layer_id;
    let accepted_token = setup_a.accepted_token;
    let inspect_open = setup_a.inspect_open;
    let case_selection = setup_a.case_selection;
    let super::setup_workspaces::KeycapsPcbState {
        active_board_id,
        keycaps_state,
        focused_keycaps_finding,
        keycaps_navigation_alive,
        layer_source,
        keycaps_fit_state,
        keycaps_settings_actions,
        resolution_signal,
        resolution,
        on_resolve,
        firmware_feedback,
        firmware_editable,
        firmware_on_edit,
        part_net_actions,
        part_input_actions,
    } = super::setup_workspaces::use_keycaps_pcb_state(super::setup_workspaces::KeycapsPcbInput {
        model,
        current_scope: current_scope.clone(),
        runtime: runtime.clone(),
        workspace,
        version,
        generation: adapter.generation,
        instance_selection,
        layout_owner: layout_owner.clone(),
    });
    let physical_setup_mount = super::setup_workspaces::use_physical_setup(
        runtime.clone(),
        guide_preferences,
        version,
        adapter.clone(),
        instance_selection,
        workspace,
    );
    let super::setup_workspaces::KeymapProjections {
        layer_actions,
        binding_actions,
        keymap_view,
        keymap_contours,
        keycaps_view,
        keycaps_contours,
        macro_actions,
    } = super::setup_workspaces::use_keymap_projections(
        super::setup_workspaces::KeymapProjectionsInput {
            runtime: runtime.clone(),
            layer_source,
            keymap_layer_id,
            workspace,
            generation: adapter.generation,
            accepted_token,
            current_scope: current_scope.clone(),
            active_board_id: active_board_id.clone(),
            instance_selection,
            resolution_signal,
        },
    );
    let on_show_mechanical_finding = super::setup_workspaces::on_show_mechanical_finding_handler(
        super::setup_workspaces::OnShowMechanicalFindingArgs {
            runtime: runtime.clone(),
            current_scope: current_scope.clone(),
            model,
            adapter_generation: adapter.generation,
            workspace,
            inspect_open,
            case_selection,
            instance_selection,
        },
    );
    let mechanical_settings = mechanical_settings_mount::use_mechanical_settings_mount(
        runtime.clone(),
        adapter.generation,
        workspace,
        instance_selection,
        case_selection,
        on_show_mechanical_finding,
    );
    (
        SetupB {
            keycaps_state,
            focused_keycaps_finding,
            keycaps_navigation_alive,
            keycaps_fit_state,
            keycaps_settings_actions,
            resolution_signal,
            resolution,
            on_resolve,
            firmware_feedback,
            firmware_editable,
            firmware_on_edit,
            part_net_actions,
            part_input_actions,
            physical_setup_mount,
            keymap_view,
            keymap_contours,
            keycaps_view,
            keycaps_contours,
            mechanical_settings,
        },
        layer_actions,
        binding_actions,
        macro_actions,
    )
}
